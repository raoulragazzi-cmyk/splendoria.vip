import assert from "node:assert/strict";
import {proposeMuseQuestion} from "../src/musa-interview-ai.js";
const input={locale:"it",track:"life",turns:[{role:"author",content:"Ricordo la mia prima giornata a scuola."}]};
let calls=0;
const good={async run(_model,payload){calls++;assert.equal(payload.messages[0].role,"system");return {response:"Chi era con te quel giorno?"}}};
const proposed=await proposeMuseQuestion(good,input);
assert.deepEqual({kind:proposed.kind,source:proposed.source},{kind:"question",source:"ai"});
assert.equal(calls,1);
assert.equal((await proposeMuseQuestion(null,input)).source,"fallback");
assert.equal((await proposeMuseQuestion({async run(){throw Error("outage")}},input)).source,"fallback");
assert.equal((await proposeMuseQuestion({async run(){return {response:"<script>alert(1)</script>?"}}},input)).source,"fallback");
assert.equal((await proposeMuseQuestion({async run(){return {response:"Uno splendido racconto del passato"}}},input)).source,"fallback");
const opening=await proposeMuseQuestion(good,{locale:"it",track:"life",turns:[]});
assert.equal(opening.source,"policy");
assert.equal(calls,1);
const review=await proposeMuseQuestion(good,{...input,turns:Array.from({length:6},()=>({role:"author",content:"Una memoria."}))});
assert.equal(review.kind,"review");
assert.equal(calls,1);
console.log("Musa adaptive AI isolated tests passed");
