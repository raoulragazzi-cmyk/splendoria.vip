import assert from "node:assert/strict";
import {appendMuseTurnAtomic} from "../src/musa-interview-atomic.js";
let statements=[],changed=[1,1];
const db={prepare(sql){return {bind(...args){return {sql,args}}}},async batch(items){statements=items;return changed.map(n=>({meta:{changes:n}}))}};
const owner={authorized:true,userId:"u1",projectId:"p1"};
await assert.rejects(appendMuseTurnAtomic(db,"s1",{...owner,authorized:false},{expectedVersion:0,content:"memory"}),/access_denied/);
for(const content of [""," ","x".repeat(10001)])await assert.rejects(appendMuseTurnAtomic(db,"s1",owner,{expectedVersion:0,content}),/invalid_turn/);
await assert.rejects(appendMuseTurnAtomic(db,"s1",owner,{expectedVersion:-1,content:"memory"}),/invalid_turn/);
const result=await appendMuseTurnAtomic(db,"s1",owner,{expectedVersion:4,content:" memory "});
assert.equal(result.version,5);
assert.equal(statements.length,2);
assert.match(statements[0].sql,/"version"="version"\+1/);
assert.match(statements[0].sql,/"version"=\?/);
assert.match(statements[1].sql,/MAX\(t\."ordinal"\)/);
assert.ok(statements[0].args.includes("u1")&&statements[1].args.includes("u1"));
assert.ok(statements[1].args.includes(5));
assert.match(statements[0].sql,/lastWriteToken/);
assert.match(statements[1].sql,/lastWriteToken/);
assert.equal(statements[0].args[0], statements[1].args[6]);
changed=[0,0];
await assert.rejects(appendMuseTurnAtomic(db,"s1",owner,{expectedVersion:4,content:"memory"}),/save_conflict/);
